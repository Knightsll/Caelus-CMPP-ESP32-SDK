#!/usr/bin/env python3
"""Run the pinned upstream microWakeWord trainer using Caelus' fixed MCU architecture."""
import argparse
import inspect
import os
import random
import runpy
import sys

os.environ.setdefault('CUDA_VISIBLE_DEVICES', '-1')
os.environ.setdefault('TF_NUM_INTRAOP_THREADS', '4')
os.environ.setdefault('TF_NUM_INTEROP_THREADS', '2')
os.environ.setdefault('OMP_NUM_THREADS', '4')
os.environ.setdefault('TF_CPP_MIN_LOG_LEVEL', '2')

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('config', nargs='?', help='training.yaml generated by wake_features.py')
    parser.add_argument('--export-only', action='store_true')
    parser.add_argument('--check-weights', action='store_true')
    args = parser.parse_args()
    import numpy as np
    import tensorflow as tf
    from microwakeword import train
    if 'train_ground_truth.reshape(-1)' not in inspect.getsource(train.train):
        raise RuntimeError('Apply scripts/microwakeword-class-weights.patch to the pinned upstream checkout first')
    if args.check_weights:
        labels = np.array([[0.], [1.]], dtype=np.float32)
        weights = np.ones(2) * np.where(labels.reshape(-1) == 0, 16., 1.)
        logits = tf.Variable([[0.], [0.]])
        with tf.GradientTape() as tape:
            loss = tf.keras.losses.BinaryCrossentropy(from_logits=True)(labels, logits, sample_weight=weights)
        gradients = tape.gradient(loss, logits).numpy().ravel()
        assert weights.shape == (2,) and abs(abs(gradients[0] / gradients[1]) - 16) < 1e-6
        print('PASS: negative example has 16x gradient weight; no batch-wide broadcasting')
        return
    if not args.config:
        parser.error('config is required unless --check-weights is used')
    random.seed(20261124)
    np.random.seed(20261124)
    tf.random.set_seed(20261124)
    sys.argv = ['microwakeword.model_train_eval', '--training_config', args.config,
                '--train', '0' if args.export_only else '1', '--restore_checkpoint', '1',
                '--test_tflite_streaming_quantized', '1', '--use_weights', 'best_weights',
                'mixednet', '--pointwise_filters', '48,48,48,48', '--repeat_in_block', '1,1,1,1',
                '--mixconv_kernel_sizes', '[5],[9],[13],[21]', '--residual_connection', '0,0,0,0',
                '--first_conv_filters', '32', '--first_conv_kernel_size', '5', '--stride', '3']
    runpy.run_module('microwakeword.model_train_eval', run_name='__main__')

if __name__ == '__main__':
    main()
